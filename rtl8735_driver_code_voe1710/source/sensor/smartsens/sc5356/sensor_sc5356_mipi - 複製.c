static int sc5356_get_info(uint32_t isp_id, struct rts_isp_sensor_info *info)
{
	int i;
	struct rts_isp_snr_pwr *up = &info->power_up;
	struct rts_isp_snr_pwr *down = &info->power_down;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;


	info->modes.mode[0].hdr = LINEAR_MODE;//RTS_ISP_HDR_NONE;
#if (RESOLUTION == 0)
	info->modes.mode[0].size.w = 2592;
	info->modes.mode[0].size.h = 1944;
#elif (RESOLUTION == 1)
	info->modes.mode[0].size.w = 2560;
	info->modes.mode[0].size.h = 1440;
#else
	info->modes.mode[0].size.w = 1092;
	info->modes.mode[0].size.h = 1944;
#endif
	info->modes.mode[0].fps = g_sc5356_fps_info_asic[0].fps;
	info->modes.num = 1;

#if (SENSOR_ID_SELECTION == 0)
	info->i2c.i2c_id = 0x36;
#else
	info->i2c.i2c_id = 0x10;
#endif
	info->i2c.addr_len = 2;
	info->i2c.data_len = 1;

	//g_status->hdr = LINEAR_MODE; //LINEAR_MODE, HDR_MODE
	info->cur_hdr_mode = g_status->hdr;

	i = 0;
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_HCLK, 0, 1000);
	//set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_HIGH, 1000);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 2000);
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_HIGH, 2000);
#if (RESOLUTION == 1)
	set_power_item(&up->items[i++], SNR_HCLK, CLK_24M, 6000);
#else
	set_power_item(&up->items[i++], SNR_HCLK, CLK_27M, 6000);
#endif
	up->num = i;
	i = 0;
	set_power_item(&down->items[i++], SNR_RST_GPIO, 0, 1000);
	set_power_item(&down->items[i++], SNR_PWDN_GPIO, 0, 1000);
	set_power_item(&down->items[i++], SNR_HCLK, 0, 1000);
	down->num = i;
		
	return RTS_ISP_OK;
}

static const struct fps_info *sc5356_get_fps_info(uint16_t fps)
{
	int i;
	for (i = 0; i < ARRAY_SIZE(g_sc5356_fps_info_asic); i++)
		if (fps == g_sc5356_fps_info_asic[i].fps)
			break;
	if (i == ARRAY_SIZE(g_sc5356_fps_info_asic))
		return NULL;
	return &g_sc5356_fps_info_asic[i];

}

static int sc5356_get_init_info(uint32_t isp_id,
				const struct rts_isp_sensor_mode *mode,
				struct rts_isp_sensor_init_info *info)
{
	const struct fps_info *fps_info;
	struct sc5356_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	status->hdr = mode->hdr;

	fps_info = sc5356_get_fps_info(mode->fps);
	if (!fps_info)
		return -RTS_ISP_EINVAL;
		
#if (RESOLUTION == 0 && FPS_15 == 1)
	set_init_i2c_regs(info->sensor_regs[0], g_sc5356_i2c_init_regs_asic_15fps, 0);
#elif(RESOLUTION == 1)
	set_init_i2c_regs(info->sensor_regs[0], g_sc5356_i2c_init_regs_asic_2k, 0);
#elif(RESOLUTION == 0)
	set_init_i2c_regs(info->sensor_regs[0], g_sc5356_i2c_init_regs_asic, 0);
#elif(RESOLUTION == 2)
	set_init_i2c_regs(info->sensor_regs[0], g_sc5356_i2c_init_regs_asic_2M, 0);
#endif
	
	info->interface.interface = SNR_INTERFACE_MIPI;
	info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
	info->interface.mipi.hs_term = 0x5;
	info->interface.type = RAW_SENSOR;
	info->interface.bit_depth = SNR_10BIT;
	info->mipi_behavor = NONE_HDR;
#if (RESOLUTION == 0)
	info->size.w = 2600;
	info->size.h = 1952;
	info->start.x = 0;
	info->start.y = 1;
#elif (RESOLUTION == 1)
	info->size.w = 2560;
	info->size.h = 1440;
	info->start.x = 0;
	info->start.y = 0;
#else
	info->size.w = 1092;
	info->size.h = 1952;
	info->start.x = 0;
	info->start.y = 0;
#endif
	info->hts = fps_info->hts;
	info->pclk = fps_info->clk;
	info->min_vts = status->min_vts = 2000;
	//info->max_vts = 69230;
	info->max_vts = info->min_vts * 15;

	status->exp_step = 1e6 * info->hts / info->pclk; /* us */
	return RTS_ISP_OK;
}
static int sc5356_start(uint32_t isp_id)
{
	struct sc5356_status *status;
	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;
	status = &g_status[isp_id];
	status->last_exposure = 0;
	return RTS_ISP_OK;
}

static uint16_t get_sensor_gain_reg(float fAGain, struct sc5356_status *status)
{
	int i;
	uint16_t gain = fAGain * 16;
	
	if (gain >= 512) {	//32x
		gain = 512;
		status->num = 5;
	} else {
		for (i = 0; i < ARRAY_SIZE(g_sc5356_gain_config) - 1; i++) {
			if (gain >= g_sc5356_gain_config[i].gainValue &&
			    gain < g_sc5356_gain_config[i + 1].gainValue) {
				gain = g_sc5356_gain_config[i].gainValue;
				status->num = i;
				break;
			}
		}
	}
	return gain;
}

static float get_sensor_real_gain(uint16_t wAGain)
{
	return wAGain / 16.0f;
}

uint16_t clip_d_word(uint16_t current, uint16_t minimum, uint16_t maximum)
{
	if (current > maximum)
		return maximum;
	if (current < minimum)
		return minimum;
	return current;
}
static int sc5356_get_tuned_again(uint32_t isp_id,
				  float again[RTS_ISP_HDR_CHAN_MAX])
{
	int gain_reg;
	struct sc5356_status *status;
	if (isp_id >= SUPPORTED_ISP_NUM || !again)
		return -RTS_ISP_EINVAL;
	status = &g_status[isp_id];
	gain_reg = get_sensor_gain_reg(again[0], status);
	again[0] = get_sensor_real_gain(gain_reg);
	return RTS_ISP_OK;
}
static int sc5356_get_tuned_dgain(uint32_t isp_id,
				  float dgain[RTS_ISP_HDR_CHAN_MAX])
{
	if (isp_id >= SUPPORTED_ISP_NUM || !dgain)
		return -RTS_ISP_EINVAL;
	dgain[0] = 1.0f;
	return RTS_ISP_OK;
}

static int sc5356_get_exposure_gain_info(uint32_t isp_id,
					 const struct rts_isp_sensor_exp_gain *exp_gain,
					 struct rts_isp_sync_regs *regs)
{
	int i;
	uint32_t vts;
	struct sc5356_status *status;
	struct rts_isp_sync_reg *reg;
	uint32_t exposure_rows;

	if (isp_id >= SUPPORTED_ISP_NUM || !exp_gain || !regs)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	vts = exp_gain->vts;
	reg = regs->reg;
	
	i = 0;
	//set_sync_i2c(&reg[i++], 0x3812, 0x00);
	if (abs(status->last_exposure - exp_gain->exposure[0]) > 0.001f) {
		exposure_rows = exp_gain->exposure[0] / status->exp_step + 0.5f;
		exposure_rows = exposure_rows << 4;
		set_sync_i2c(&reg[i++], 0x3e00, (exposure_rows & 0xff0000) >> 16);
		set_sync_i2c(&reg[i++], 0x3e01, (exposure_rows & 0xff00) >> 8);
		set_sync_i2c(&reg[i++], 0x3e02, exposure_rows & 0xff);
		status->last_exposure = exp_gain->exposure[0];
	}
	set_sync_i2c(&reg[i++], 0x3e09, g_sc5356_gain_config[status->num].regValue);
	set_sync_i2c(&reg[i++], 0x320E, vts >> 8);
	set_sync_i2c(&reg[i++], 0x320F, vts & 0xff);
	//set_sync_i2c(&reg[i++], 0x3812, 0x30);
	regs->num = i;
	return RTS_ISP_OK;
}

static int sc5356_set_mirror_flip(uint32_t isp_id,
								  struct rts_isp_sensor_mirror_flip *mf_info)
{
	int i;
	uint16_t bySnrImgDir;
	struct rts_isp_sync_reg *reg;

	bySnrImgDir = mf_info->mirror_en != 0;
	bySnrImgDir = (mf_info->flip_en != 0) << 1 | bySnrImgDir;
	mf_info->delay_frames = 1;

	i = 0;
	reg = mf_info->regs.reg;
	switch(bySnrImgDir)//
	{
	#if (ORIENTATION == 0)
		case 0: //normal
		default:
            set_sync_i2c(&reg[i++], 0x3221, 0x66);
			break;
		case 2: 	// Mirror
           	set_sync_i2c(&reg[i++], 0x3221, 0x06);
			break;
		case 1: 		// VFlip
            set_sync_i2c(&reg[i++], 0x3221, 0x60);
			break;
		case 3: 	// Rotate
            set_sync_i2c(&reg[i++], 0x3221, 0x00);
			break;
	#else
		case 0: //normal
		default:
            set_sync_i2c(&reg[i++], 0x3221, 0x00);
			break;
		case 2: 	// Mirror
           	set_sync_i2c(&reg[i++], 0x3221, 0x60);
			break;
		case 1: 		// VFlip
            set_sync_i2c(&reg[i++], 0x3221, 0x06);
			break;
		case 3: 	// Rotate
            set_sync_i2c(&reg[i++], 0x3221, 0x66);
			break;
	#endif
	}
	mf_info->regs.num = i;
	return RTS_ISP_OK;
}

static int sc5356_check(uint32_t isp_id)
{
	int ret;
	int id;
	struct rts_isp_i2c_reg reg;

    rts_isp_sensor_access_prepare();

	reg.addr = 0x3107;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret) {
	    rts_isp_sensor_access_unprepare();
		return ret;
	}
	id = reg.data << 8;

	reg.addr = 0x3108;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);

    rts_isp_sensor_access_unprepare();

	if (ret)
		return ret;
	id |= reg.data;
	
	if (id == 0xEE4B)
		return RTS_ISP_OK;
	else
		return -RTS_ISP_EINVAL;
}

