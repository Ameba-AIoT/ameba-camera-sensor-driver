static int os04e10_get_init_info(uint32_t isp_id,
				const struct rts_isp_sensor_mode *mode,
				   struct rts_isp_sensor_init_info *info)
{
	struct os04e10_status *status;
	const struct fps_info *fps_info;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	status->hdr = mode->hdr;

	//fps_info = os04e10_get_fps_info(mode->fps);

	//if (!fps_info)
	//	return -RTS_ISP_EINVAL;

	set_init_i2c_regs(info->sensor_regs[0],
			g_os04e10_i2c_init_regs, 0);

	info->interface.interface = SNR_INTERFACE_MIPI;
	info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
	info->interface.mipi.hs_term = 0x07;
	info->interface.type = RAW_SENSOR;
	info->interface.bit_depth = SNR_10BIT;
	info->mipi_behavor = NONE_HDR;

	info->size.w = 2052;
	info->size.h = 2052;
	info->start.x = 54;
	info->start.y = 55;

	info->hts = 1616*2;
	info->min_vts = status->min_vts = 2164;
	info->pclk = 209821440;
	info->max_vts = 65535 - info->min_vts;
	status->exp_step = 1e6 * info->hts / info->pclk; /* us */
	info->exposure_step = status->exp_step;
	//printf("max_vts  = %d  , min_vts = %d \n\r", info->max_vts,info->min_vts);

	return RTS_ISP_OK;
}

static int os04e10_start(uint32_t isp_id)
{
	struct os04e10_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	status->last_exposure[0] = 0;

	return RTS_ISP_OK;
}

static int os04e10_get_exposure_range(uint32_t isp_id, uint32_t vts,
					 float ratio[RTS_ISP_HDR_CHAN_MAX - 1],
					 float min_exposure[RTS_ISP_HDR_CHAN_MAX],
					 float max_exposure[RTS_ISP_HDR_CHAN_MAX])
{
	struct os04e10_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	if (status->hdr == LINEAR_MODE) {
		min_exposure[0] =  2 * status->exp_step;
		max_exposure[0] = (vts - 8) * status->exp_step;
	}
	//printf("exp_range_vts = %d  \n\r", vts );


	return RTS_ISP_OK;
}

/* OV gain: real_gain = reg / 128.0, 1x = 0x80, max 15.5x = 0x7C0 */
static uint16_t get_sensor_gain_reg(float fgain)
{
	uint16_t reg_value = 0;

	reg_value = (uint16_t)(fgain * 128.0f);
	if (reg_value < 0x7c0)
		return reg_value;
	else
		return 0x7c0;
}

static float get_sensor_real_gain(uint16_t reg_value)
{
	return ((float)reg_value / 128.0f);
}

uint32_t clip_d_word(uint32_t current, uint32_t minimum, uint32_t maximum)
{
	if (current > maximum)
		return maximum;
	if (current < minimum)
		return minimum;
	return current;
}

static int os04e10_get_tuned_again(uint32_t isp_id,
				  float again[RTS_ISP_HDR_CHAN_MAX])
{
	uint16_t gain_reg;
	struct os04e10_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	gain_reg = get_sensor_gain_reg(again[0]);
	again[0] = get_sensor_real_gain(gain_reg);

	return RTS_ISP_OK;
}

static int os04e10_get_tuned_dgain(uint32_t isp_id,
				  float dgain[RTS_ISP_HDR_CHAN_MAX])
{
	if (isp_id >= SUPPORTED_ISP_NUM || !dgain)
		return -RTS_ISP_EINVAL;

	dgain[0] = 1.0f;

	return RTS_ISP_OK;
}

