static int gc5035_get_info(uint32_t isp_id, struct rts_isp_sensor_info *info)
{
	int i;
	struct rts_isp_snr_pwr *up = &info->power_up;
	struct rts_isp_snr_pwr *down = &info->power_down;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	info->modes.mode[0].hdr = LINEAR_MODE;//RTS_ISP_HDR_NONE;
	info->modes.mode[0].size.w = 2592;
	info->modes.mode[0].size.h = 1944;
	info->modes.mode[0].fps = g_gc5035_fps_info[0].fps;
	info->modes.num = 1;

	info->i2c.i2c_id = 0x37;
	info->i2c.addr_len = 1;
	info->i2c.data_len = 1;

	//g_status->hdr = LINEAR_MODE; //LINEAR_MODE, HDR_MODE
	info->cur_hdr_mode = g_status->hdr;
	i = 0;
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_HCLK, 0, 1000);
	//set_power_item(&up->items[i++], SNR_IO_POWER, PWR_1V8, 1000);
	//set_power_item(&up->items[i++], SNR_CORE_POWER, PWR_1V2, 1000);
	//set_power_item(&up->items[i++], SNR_ANALOG_POWER, PWR_2V8, 1000);
#if MCLK_TYPE == 0
	set_power_item(&up->items[i++], SNR_HCLK, CLK_12M, 1000);
#else
	set_power_item(&up->items[i++], SNR_HCLK, CLK_27M, 1000);
#endif

	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_HIGH, 1000);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 1000);
	up->num = i;
	i = 0;
	set_power_item(&down->items[i++], SNR_RST_GPIO, 0, 10000);
	set_power_item(&down->items[i++], SNR_PWDN_GPIO, 0, 100000);
	set_power_item(&down->items[i++], SNR_HCLK, 0, 10000);
	down->num = i;

	return RTS_ISP_OK;
}

static const struct fps_info *gc5035_get_fps_info(uint16_t fps)
{
	int i;

	for (i = 0; i < ARRAY_SIZE(g_gc5035_fps_info); i++)
		if (fps == g_gc5035_fps_info[i].fps)
			break;
	if (i == ARRAY_SIZE(g_gc5035_fps_info))
		return NULL;

	return &g_gc5035_fps_info[i];
}

static int gc5035_get_init_info(uint32_t isp_id,
				const struct rts_isp_sensor_mode *mode,
				struct rts_isp_sensor_init_info *info)
{
	const struct fps_info *fps_info;
	struct gc5035_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	status->hdr = mode->hdr;

	fps_info = gc5035_get_fps_info(mode->fps);
	if (!fps_info)
		return -RTS_ISP_EINVAL;

#if MCLK_TYPE == 0
	set_init_i2c_regs(info->sensor_regs[0], g_gc5035_i2c_init_regs_24M, 0);
#else
	set_init_i2c_regs(info->sensor_regs[0], g_gc5035_i2c_init_regs_27M, 0);
#endif
	info->interface.interface = SNR_INTERFACE_MIPI;
	info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
	info->interface.mipi.hs_term = 0x6;
	info->interface.type = RAW_SENSOR;
	info->interface.bit_depth = SNR_10BIT;
	info->mipi_behavor = NONE_HDR;
#if MCLK_TYPE == 0
	info->size.w = 2596;
	info->size.h = 1948;
	info->start.x = 0;
	info->start.y = 0;
#else
	info->size.w = 2594;
	info->size.h = 1946;
	info->start.x = 0;
	info->start.y = 0;
#endif

	info->hts = fps_info->hts;
	info->pclk = fps_info->clk;
	info->min_vts = 2004;
	info->max_vts = 10020;

	status->exp_step = 1e6 * info->hts / info->pclk; /* us */
	status->min_vts = info->min_vts;
	status->last_exposure = 0;
	return RTS_ISP_OK;
}

static int gc5035_start(uint32_t isp_id)
{
	struct gc5035_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	status->last_exposure = 0;

	return RTS_ISP_OK;
}

static uint16_t get_sensor_gain_reg(float fgain, struct gc5035_status *status)
{
	int i;
	uint16_t gain = fgain * 64;

	if (gain >= 998) {
		gain = 998;
		status->num = 16;
	} else {
		for (i = 0; i < ARRAY_SIZE(g_gc5035_gain_config) - 1; i++) {
			if (gain >= g_gc5035_gain_config[i].value &&
			    gain < g_gc5035_gain_config[i + 1].value) {
				gain = g_gc5035_gain_config[i].value;
				status->num = i;
				break;
			}
		}
	}
	return gain;
}

static float get_sensor_real_gain(uint16_t reg_value)
{
	return reg_value / 64.0f;
}

static int gc5035_get_tuned_again(uint32_t isp_id,
				  float again[RTS_ISP_HDR_CHAN_MAX])
{
	int gain_reg;
	struct gc5035_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !again)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	gain_reg = get_sensor_gain_reg(again[0], status);
	again[0] = get_sensor_real_gain(gain_reg);

	return RTS_ISP_OK;
}

static int gc5035_get_tuned_dgain(uint32_t isp_id,
				  float dgain[RTS_ISP_HDR_CHAN_MAX])
{
	if (isp_id >= SUPPORTED_ISP_NUM || !dgain)
		return -RTS_ISP_EINVAL;

	dgain[0] = 1.0f;

	return RTS_ISP_OK;
}

static int gc5035_get_exposure_gain_info(uint32_t isp_id,
					 const struct rts_isp_sensor_exp_gain *exp_gain,
					 struct rts_isp_sync_regs *regs)
{
	int i;
	uint32_t vts;
	struct gc5035_status *status;
	struct rts_isp_sync_reg *reg;
	uint16_t exposure_rows;

	if (isp_id >= SUPPORTED_ISP_NUM || !exp_gain || !regs)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	vts = exp_gain->vts;
	reg = regs->reg;

	i = 0;
	set_sync_i2c(&reg[i++], 0xfe, 0x00);
	if (abs(status->last_exposure - exp_gain->exposure[0]) > 0.001f) {
		exposure_rows = exp_gain->exposure[0] / status->exp_step + 0.5f;
		set_sync_i2c(&reg[i++], 0x03, exposure_rows >> 8);
		set_sync_i2c(&reg[i++], 0x04, exposure_rows & 0xff);
		status->last_exposure = exp_gain->exposure[0];
	}

	set_sync_i2c(&reg[i++], 0xb6,	g_gc5035_gain_config[status->num].reg_b6);
	set_sync_i2c(&reg[i++], 0x41, vts >> 8);
	set_sync_i2c(&reg[i++], 0x42, vts & 0xff);

	regs->num = i;

	return RTS_ISP_OK;
}

static int gc5035_set_mirror_flip(uint32_t isp_id,
								  struct rts_isp_sensor_mirror_flip *mf_info)
{
	int i;
	uint16_t bySnrImgDir;
	struct rts_isp_sync_reg *reg;

	bySnrImgDir = mf_info->mirror_en != 0;
	bySnrImgDir = (mf_info->flip_en != 0) << 1 | bySnrImgDir;
	mf_info->delay_frames = 1;

	i = 0;
	reg = mf_info->regs.reg;
	switch(bySnrImgDir)
	{
		case 0: //normal
		default:
			set_sync_i2c(&reg[i++], 0xfe, 0x00);
			set_sync_i2c(&reg[i++], 0x17, 0x83);
			set_sync_i2c(&reg[i++], 0xfe, 0x01);
			set_sync_i2c(&reg[i++], 0x92, 0x07);
			set_sync_i2c(&reg[i++], 0x94, 0x07);
			
		break;
		case 1: 	// Mirror
			set_sync_i2c(&reg[i++], 0xfe, 0x00);
			set_sync_i2c(&reg[i++], 0x17, 0x82);
			set_sync_i2c(&reg[i++], 0xfe, 0x01);
			set_sync_i2c(&reg[i++], 0x92, 0x07);
			set_sync_i2c(&reg[i++], 0x94, 0x08);
		break;
		case 2: 		// VFlip
			set_sync_i2c(&reg[i++], 0xfe, 0x00);
			set_sync_i2c(&reg[i++], 0x17, 0x81);
			set_sync_i2c(&reg[i++], 0xfe, 0x01);
			set_sync_i2c(&reg[i++], 0x92, 0x08);
			set_sync_i2c(&reg[i++], 0x94, 0x07);
		break;
		case 3: 	// Rotate
			set_sync_i2c(&reg[i++], 0xfe, 0x00);
			set_sync_i2c(&reg[i++], 0x17, 0x80);
			set_sync_i2c(&reg[i++], 0xfe, 0x01);
			set_sync_i2c(&reg[i++], 0x92, 0x08);
			set_sync_i2c(&reg[i++], 0x94, 0x08);
		break;
	}
	mf_info->regs.num = i;
	return RTS_ISP_OK;
}

static int gc5035_check(uint32_t isp_id)
{
	int ret;
	int id;
	struct rts_isp_i2c_reg reg;

    rts_isp_sensor_access_prepare();

	reg.addr = 0xf0;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret) {
	    rts_isp_sensor_access_unprepare();
		return ret;
	}
	id = reg.data << 8;

	reg.addr = 0xf1;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);

    rts_isp_sensor_access_unprepare();

	if (ret)
		return ret;
	id |= reg.data;

	if (id == 0x5035)
		return RTS_ISP_OK;
	else
		return -RTS_ISP_EINVAL;
}

