static int vd550g_check(uint32_t isp_id)
{
	int ret;
	int id;
	struct rts_isp_i2c_reg reg;


	//WaitValueEx(4, 0x0001, 0x47, 1); // (val=1396000560) / UI.STATUS.DEVICE_MODEL_ID
	//WaitValueEx(4, 0x0000, 0x30, 1); // (val=1396000560) / UI.STATUS.DEVICE_MODEL_ID

    rts_isp_sensor_access_prepare();

	reg.addr = 0x0000;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret) {
	    rts_isp_sensor_access_unprepare();
		return ret;
	}
	id = reg.data << 8;

	reg.addr = 0x0001;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret) {
	    rts_isp_sensor_access_unprepare();
		return ret;
	}
	id |= reg.data;	
	
	if (id == 0x3047)
		return RTS_ISP_OK;
	else
		return -RTS_ISP_EINVAL;
}

