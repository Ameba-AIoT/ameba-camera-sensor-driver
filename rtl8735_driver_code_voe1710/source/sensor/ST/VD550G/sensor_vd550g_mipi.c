static const struct fps_info *vd550g_get_fps_info(uint16_t fps)
{
	int i;

		for (i = 0; i < ARRAY_SIZE(g_vd550g_fps_info_asic); i++)
			if (fps == g_vd550g_fps_info_asic[i].fps)
				break;
		if (i == ARRAY_SIZE(g_vd550g_fps_info_asic))
			return NULL;
		return &g_vd550g_fps_info_asic[i];

}

static int vd550g_get_init_info(uint32_t isp_id,
				const struct rts_isp_sensor_mode *mode,
				struct rts_isp_sensor_init_info *info)
{
	const struct fps_info *fps_info;
	struct vd550g_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	status->hdr = mode->hdr;

	fps_info = vd550g_get_fps_info(mode->fps);
	if (!fps_info)
		return -RTS_ISP_EINVAL;

	set_init_i2c_regs(info->sensor_regs[0], g_vd550g_i2c_init_regs_asic, 0);

	info->interface.interface = SNR_INTERFACE_MIPI;
	info->interface.mipi.lanes = MIPI_LANE0;
	info->interface.mipi.hs_term = 0x5;
	info->interface.type = RAW_SENSOR;
	info->interface.bit_depth = SNR_10BIT;
	info->mipi_behavor = NONE_HDR;

	info->size.w = 640;
	info->size.h = 600;
	info->start.x = 0;
	info->start.y = 0;

	info->hts = fps_info->hts;
	info->pclk = fps_info->clk;
	info->min_vts = status->min_vts = 703;
	info->max_vts = 4218;

	status->exp_step = 1e6 * info->hts / info->pclk; /* us */
	//info->exposure_step = status->exp_step;

	return RTS_ISP_OK;
}

static int vd550g_start(uint32_t isp_id)
{
	struct vd550g_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	status->last_exposure = 0;

	return RTS_ISP_OK;
}

static uint16_t get_sensor_gain_reg(float fgain, struct vd550g_status *status)
{
	int i;
	uint16_t gain = fgain * 64;
	
	if (gain >= 256) {	//4x
		gain = 256;
		status->num = 24;
	} else {
		for (i = 0; i < ARRAY_SIZE(g_vd550g_gain_config) - 1; i++) {
			if (gain >= g_vd550g_gain_config[i].value &&
			    gain < g_vd550g_gain_config[i + 1].value) {
				gain = g_vd550g_gain_config[i].value;
				status->num = i;
				break;
			}
		}
	}
	return gain;
}

static float get_sensor_real_gain(uint16_t reg_value)
{
	return reg_value / 64.0f;
}

static int vd550g_get_tuned_again(uint32_t isp_id,
				  float again[RTS_ISP_HDR_CHAN_MAX])
{
	int gain_reg;
	struct vd550g_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !again)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	gain_reg = get_sensor_gain_reg(again[0], status);
	again[0] = get_sensor_real_gain(gain_reg);

	return RTS_ISP_OK;
}

static int vd550g_get_tuned_dgain(uint32_t isp_id,
				  float dgain[RTS_ISP_HDR_CHAN_MAX])
{
	if (isp_id >= SUPPORTED_ISP_NUM || !dgain)
		return -RTS_ISP_EINVAL;

	dgain[0] = 1.0f;

	return RTS_ISP_OK;
}

static int vd550g_get_exposure_gain_info(uint32_t isp_id,
					 const struct rts_isp_sensor_exp_gain *exp_gain,
					 struct rts_isp_sync_regs *regs)
{
	int i;
	uint32_t vts;
	struct vd550g_status *status;
	struct rts_isp_sync_reg *reg;
	uint16_t exposure_rows;

	if (isp_id >= SUPPORTED_ISP_NUM || !exp_gain || !regs)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	vts = exp_gain->vts;
	reg = regs->reg;

	i = 0;
	//set_sync_i2c(&reg[i++], 0xfe, 0x00);
	if (abs(status->last_exposure - exp_gain->exposure[0]) > 0.001f) {
		exposure_rows = exp_gain->exposure[0] / status->exp_step + 0.5f;
		set_sync_i2c(&reg[i++], 0x044f, exposure_rows >> 8);
		set_sync_i2c(&reg[i++], 0x044e, exposure_rows & 0xff);
		status->last_exposure = exp_gain->exposure[0];
	}
	set_sync_i2c(&reg[i++], 0x044d, g_vd550g_gain_config[status->num].reg);
	//set_sync_i2c(&reg[i++], 0xb3, g_gc2035_gain_config[status->num].reg_b3);
	//set_sync_i2c(&reg[i++], 0xb4, g_gc2035_gain_config[status->num].reg_b4);
	//set_sync_i2c(&reg[i++], 0xb8, g_gc2035_gain_config[status->num].reg_b8);
	//set_sync_i2c(&reg[i++], 0xb9, g_gc2035_gain_config[status->num].reg_b9);
	//set_sync_i2c(&reg[i++], 0x41, vts >> 8);
	//set_sync_i2c(&reg[i++], 0x42, vts & 0xff);
	//set_sync_i2c(&reg[i++], 0xfe, 0x04);
	regs->num = i;

	return RTS_ISP_OK;
}
