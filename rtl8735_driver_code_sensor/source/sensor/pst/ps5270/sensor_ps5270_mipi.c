static uint16_t get_sensor_gain_reg(float fAGain, struct ps5270_status *status)
{
	int i;
	uint16_t gain = fAGain * 1024;
	for (i = 0; i < (181 - 1); i++) {
		if (gain >= ps5270_gain_table[i] &&
		    gain < ps5270_gain_table[i+1]) {
			gain = ps5270_gain_table[i];
			//status->num = i;
			break;
		}
	}
	if(ps5270_gain_table[i] > AG_HS_NODE)
	{
		g_sghd_flg = 0;	// HS Mode
	}
	else if(ps5270_gain_table[i] < AG_LS_NODE)
	{
		g_sghd_flg = 1;	// LS Mode	
	}
	// Calculate gain index
    status->num = (g_sghd_flg == 0)? (i-64):i;
	return gain;
}

static float get_sensor_real_gain(uint16_t wAGain)
{
	return wAGain / 1024.0f;
}

static int ps5270_get_tuned_again(uint32_t isp_id,
				  float again[RTS_ISP_HDR_CHAN_MAX])
{
	int gain_reg;
	struct ps5270_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !again)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	gain_reg = get_sensor_gain_reg(again[0], status);
	again[0] = get_sensor_real_gain(gain_reg);

	return RTS_ISP_OK;
}

