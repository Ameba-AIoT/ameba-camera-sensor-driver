static int ps5270_check(uint32_t isp_id)
{
	int ret;
	int id;
	struct rts_isp_i2c_reg reg;
	
	rts_isp_sensor_access_prepare();
	reg.addr = 0xEF;
	reg.data = 0x00;
	ret = rts_isp_write_sensor_reg(isp_id, &reg);
	if (ret) {
	    rts_isp_sensor_access_unprepare();
		return ret;
	}

	reg.addr = 0x00;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret) {
	    rts_isp_sensor_access_unprepare();
		return ret;
	}
	id = reg.data << 8;

	reg.addr = 0x01;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret) {
	    rts_isp_sensor_access_unprepare();
		return ret;
	}
	id |= reg.data;
	
	rts_isp_sensor_access_unprepare();
	
	#if (SENSOR_HDR == 0)
		printf("ps5270_check: SensorID=0x%x, HDR=Off\r\n",id);
	#else
		printf("ps5270_check: SensorID=0x%x, HDR=On\r\n",id);
	#endif
	
	if (id == 0x5270)
		return RTS_ISP_OK;
	else
		return -RTS_ISP_EINVAL;
}

