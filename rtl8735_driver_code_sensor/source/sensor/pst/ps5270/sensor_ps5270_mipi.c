static int ps5270_get_exposure_gain_info(uint32_t isp_id,
					 const struct rts_isp_sensor_exp_gain *exp_gain,
					 struct rts_isp_sync_regs *regs)
{
	int i;
	uint32_t vts;
	struct ps5270_status *status;
	struct rts_isp_sync_reg *reg;
	uint16_t exposure_rows;
	unsigned int ny, ne, ne_patch;

	if (isp_id >= SUPPORTED_ISP_NUM || !exp_gain || !regs)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	vts = exp_gain->vts - 1;
	reg = regs->reg;
	
	/*
	if(!g_sns_const1)
	{
		//rts_isp_sensor_access_prepare();
		ps5270_get_g_sns_const1(isp_id);
		//rts_isp_sensor_access_unprepare();
	}
	*/

	i = 0;
	g_total_lines = vts;
	set_sync_i2c(&reg[i++], 0xEF, 0x01);
	if (abs(status->last_exposure - exp_gain->exposure[0]) > 0.001f) {
		exposure_rows = exp_gain->exposure[0] / status->exp_step + 0.5f;
		g_lines = ((g_total_lines - 4) > exposure_rows)?((3 < exposure_rows)?exposure_rows:3):(g_total_lines - 4);	// 4 <= Ny <= LPF-3
		ny = g_total_lines - g_lines;
		ne_patch = NE_PATCH_LB + ((ny*NE_PATCH_SCALE)>>8);
		if (ne_patch > NE_PATCH_UB)	ne_patch = NE_PATCH_UB;
		ne = g_sns_const1 - ne_patch;
		set_sync_i2c(&reg[i++], 0x0C, (ny>>8));
		set_sync_i2c(&reg[i++], 0x0D, ny&0xFF);
		set_sync_i2c(&reg[i++], 0x0E, (ne>>8));
		set_sync_i2c(&reg[i++], 0x0F, ne&0xFF);
		set_sync_i2c(&reg[i++], 0x5F, (ne_patch>>8));
		set_sync_i2c(&reg[i++], 0x60, ne_patch&0xFF);
		status->last_exposure = exp_gain->exposure[0];
	}
	set_sync_i2c(&reg[i++], 0x0A, (g_total_lines>>8));
	set_sync_i2c(&reg[i++], 0x0B, g_total_lines&0xFF);
	set_sync_i2c(&reg[i++], 0x83, status->num);
	set_sync_i2c(&reg[i++], 0x18, g_sghd_flg);
	set_sync_i2c(&reg[i++], 0x09, 0x01);
	regs->num = i;
	return RTS_ISP_OK;
}

