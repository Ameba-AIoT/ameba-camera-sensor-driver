static int ps5270_get_info(uint32_t isp_id, struct rts_isp_sensor_info *info)
{
	int i;
	struct rts_isp_snr_pwr *up = &info->power_up;
	struct rts_isp_snr_pwr *down = &info->power_down;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;


	info->modes.mode[0].hdr = LINEAR_MODE;//RTS_ISP_HDR_NONE;
	info->modes.mode[0].size.w = 1536;
	info->modes.mode[0].size.h = 1536;
	info->modes.mode[0].fps = g_ps5270_fps_info_asic[0].fps;
	info->modes.num = 1;
	info->i2c.i2c_id = 0x48;
	info->i2c.addr_len = 1;
	info->i2c.data_len = 1;

	info->cur_hdr_mode = g_status->hdr;

	i = 0;
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_HCLK, 0, 1000);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 2000);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 2000);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 3000);
	set_power_item(&up->items[i++], SNR_HCLK, CLK_27M, 5000);

	up->num = i;
	i = 0;
	set_power_item(&down->items[i++], SNR_PWDN_GPIO, GPIO_HIGH, 0);
	set_power_item(&down->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	set_power_item(&down->items[i++], SNR_HCLK, 0, 3000);
	down->num = i;
	return RTS_ISP_OK;
}

static const struct fps_info *ps5270_get_fps_info(uint16_t fps)
{
	int i;
	for (i = 0; i < ARRAY_SIZE(g_ps5270_fps_info_asic); i++)
		if (fps == (int)g_ps5270_fps_info_asic[i].fps)
			break;
	if (i == ARRAY_SIZE(g_ps5270_fps_info_asic))
		return NULL;
	return &g_ps5270_fps_info_asic[i];

}

static int ps5270_get_g_sns_const1(uint32_t isp_id)
{
	struct rts_isp_i2c_reg reg;
	uint bReg0E, bReg0F, bReg5F, bReg60;
	int ret;
	reg.addr = 0xef;
	reg.data = 0x01;
	rts_isp_write_sensor_reg(isp_id, &reg);
	reg.addr = 0x0E;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	bReg0E = reg.data;
	reg.addr = 0x0F;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	bReg0F = reg.data;
	reg.addr = 0x5F;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	bReg5F = reg.data;
	reg.addr = 0x60;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret)
		return ret;
	bReg60 = reg.data;
	g_sns_const1 = (bReg0E<<8|bReg0F) + (bReg5F <<8|bReg60);
}

static int ps5270_get_init_info(uint32_t isp_id,
				const struct rts_isp_sensor_mode *mode,
				struct rts_isp_sensor_init_info *info)
{
	const struct fps_info *sfps_info;
	struct ps5270_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	sfps_info = ps5270_get_fps_info(mode->fps);
	if (!sfps_info)
		return -RTS_ISP_EINVAL;
#if (SENSOR_HDR == 0)
	set_init_i2c_regs(info->sensor_regs[0],
			  g_ps5270_i2c_init_regs_asic, 5000);
#else
	set_init_i2c_regs(info->sensor_regs[0],
			  g_ps5270_HDR_i2c_init_regs_asic, 5000);
#endif
	
	set_init_i2c_regs(info->sensor_regs[1],
			  g_ps5270_i2c_init_regs_asic2, 1000);

	info->interface.interface = SNR_INTERFACE_MIPI;
	info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
	info->interface.mipi.hs_term = 0x2;
	info->interface.type = RAW_SENSOR;
#if (SENSOR_HDR == 0)
	info->interface.bit_depth = SNR_10BIT;
#else
	info->interface.bit_depth = SNR_12BIT;
#endif
	info->mipi_behavor = NONE_HDR;
	info->size.w = 1540;
	info->size.h = 1540;
	info->start.x = 0;
	info->start.y = 1;
	info->hts = sfps_info->hts;
	info->pclk = sfps_info->clk;
#if (SENSOR_HDR == 0)
	info->min_vts = status->min_vts = 1600;
	info->max_vts = 8000;
#else
	info->min_vts = status->min_vts = 1630;
	info->max_vts = 8150;
#endif

	status->exp_step = 1e6 * info->hts / info->pclk; /* us */
	return RTS_ISP_OK;
}
static int ps5270_start(uint32_t isp_id)
{
	struct ps5270_status *status;
	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;
	status = &g_status[isp_id];
	status->last_exposure = 0;
	return RTS_ISP_OK;
}

uint16_t clip_d_word(uint16_t current, uint16_t minimum, uint16_t maximum)
{
	if (current > maximum)
		return maximum;
	if (current < minimum)
		return minimum;
	return current;
}

