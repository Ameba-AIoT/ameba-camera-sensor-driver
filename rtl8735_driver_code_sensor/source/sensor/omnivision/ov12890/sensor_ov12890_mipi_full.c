static int ov12890_get_info(uint32_t isp_id, struct rts_isp_sensor_info *info)
{
	int i;
	struct rts_isp_snr_pwr *up = &info->power_up;
	struct rts_isp_snr_pwr *down = &info->power_down;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	i = 0;
#if(BINNING == 0)	
	info->modes.mode[i].hdr = LINEAR_MODE;
	info->modes.mode[i].size.w = 4032;
	info->modes.mode[i].size.h = 3024;
	info->modes.mode[i].fps = 8;
	i++;

	info->modes.mode[i].hdr = HDR_MODE;
	info->modes.mode[i].size.w = 4032;
	info->modes.mode[i].size.h = 3024;
	info->modes.mode[i].fps = 8;			//@MLCK=24MHz
#else
	info->modes.mode[i].hdr = LINEAR_MODE;
	info->modes.mode[i].size.w = 2048;     
	info->modes.mode[i].size.h = 1536;     
	info->modes.mode[i].fps = 30.0f;
	i++;

	info->modes.mode[i].hdr = HDR_MODE;
	info->modes.mode[i].size.w = 2048;     //2048
	info->modes.mode[i].size.h = 1536;     //1536
	info->modes.mode[i].fps = 30.0f;			//@MLCK=24MHz
#endif	
	i++;
	info->modes.num = i;
	
	info->i2c.i2c_id = 0x36;										//Write=0x52/Read=0x53
	info->i2c.addr_len = 2;
	info->i2c.data_len = 1;
	info->cur_hdr_mode = g_status->hdr;

	i = 0;
	
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_LOW, 1000);	
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 0);
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_HIGH, 5000);
#if(BINNING == 0)	
	set_power_item(&up->items[i++], SNR_HCLK, CLK_12M, 5000);
#else
	set_power_item(&up->items[i++], SNR_HCLK, CLK_24M, 5000);
#endif	
	up->num = i;
	i = 0;
	set_power_item(&down->items[i++], SNR_HCLK, 0, 50);
	set_power_item(&down->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	down->num = i;

	return RTS_ISP_OK;
}

