static int sc485sl_get_exposure_range(uint32_t isp_id, uint32_t vts,
				     float ratio[RTS_ISP_HDR_CHAN_MAX - 1],
				     float min_exposure[RTS_ISP_HDR_CHAN_MAX],
				     float max_exposure[RTS_ISP_HDR_CHAN_MAX])
{
	struct sc485sl_status *status;


	if (isp_id >= SUPPORTED_ISP_NUM)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];


	if (status->hdr == HDR_MODE) {
		uint32_t sensor_long_exp_min, sensor_short_exp_min, sensor_long_exp_max, sensor_short_exp_max;

		//interval between long and short exposure frame = SE start point {3e33, 3e23, 3e24} = 0xc4 = 196
		
		sensor_long_exp_min = 2;
		sensor_short_exp_min = 2;
		sensor_long_exp_max = vts - interval_between_long_short- 13;
		sensor_short_exp_max = interval_between_long_short - 11;

		uint32_t tmp1,tmp2;
		tmp1 = sensor_long_exp_max;
		tmp2 = sensor_short_exp_max * ratio[0];
		//debug("vts=%d, sensor_long_exp_max=%d, tmp1=%d, tmp2=%d\n",vts,sensor_long_exp_max, tmp1,tmp2);
		tmp1 = tmp1 < tmp2 ? tmp1 : tmp2;
		
		max_exposure[1] = sensor_short_exp_max * status->exp_step;
		min_exposure[1] = sensor_short_exp_min * status->exp_step;
		max_exposure[0] = tmp1 * status->exp_step;
		min_exposure[0] = min_exposure[1] * ratio[0];
	
		//debug("[Exp Range]long_max_exp_=%f, long_min_exp=%f, ratio[0]=%f\n", max_exposure[0], min_exposure[0],ratio[0]);
		//debug("[Exp Range]short_max_exp_=%f, short_min_exp=%f\n", max_exposure[1], min_exposure[1]);
	}
	else{
		uint8_t sensor_long_exp_min;
		sensor_long_exp_min = 1;
		min_exposure[0] = sensor_long_exp_min * status->exp_step;
		max_exposure[0] = (vts - 8) * status->exp_step;
		//debug("expusre_min = %1.f , expusre_max = %1.f\n", min_exposure[0],max_exposure[0]);
	}

	return RTS_ISP_OK;
}

static uint16_t get_sensor_gain_reg(float fgain, struct sc485sl_status *status)
{
	uint16_t reg_value = 0;
	int i;

	if (fgain >= ANALOG_GAIN_MAX_RATIO) {
		reg_value = 0x8f3f;
		status->gain_reg_num = (uint8_t)(ARRAY_SIZE(gain_mapping) - 1);

	} else {
		for (i = 0; i < ((ARRAY_SIZE(gain_mapping)) - 1); i++) {
			if ((gain_mapping[i].total_gain <= fgain) &&
			    (fgain < gain_mapping[i + 1].total_gain)) {
				reg_value = gain_mapping[i].ana_gain | gain_mapping[i].fine_gain;
				status->gain_reg_num = i;
				break;
			}
		}
	}
	return reg_value;
}

static float get_sensor_real_gain(uint16_t reg_value)
{
	float gain = 0.0;
	int i;

	if (reg_value >= 0x8f3f) {
		gain = ANALOG_GAIN_MAX_RATIO;
	} else {
		for (i = 0; i < ((ARRAY_SIZE(gain_mapping)) - 1); i++) {
			if (reg_value == (gain_mapping[i].ana_gain |
			    gain_mapping[i].fine_gain)) {
				gain = gain_mapping[i].total_gain;
				break;
			}
		}
	}

	return gain;
}

uint16_t clip_d_word(uint16_t current, uint16_t minimum, uint16_t maximum)
{
	if (current > maximum)
		return maximum;
	if (current < minimum)
		return minimum;
	return current;
}

static int sc485sl_get_tuned_again(uint32_t isp_id,
				  float again[RTS_ISP_HDR_CHAN_MAX])
{
	int gain_reg;
	struct sc485sl_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !again)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	gain_reg = get_sensor_gain_reg(again[0], status);
	again[0] = get_sensor_real_gain(gain_reg);
	if (status->hdr == HDR_MODE) {
		gain_reg = get_sensor_gain_reg(again[1], status);
		again[1] = get_sensor_real_gain(gain_reg);
	}

	return RTS_ISP_OK;
}

