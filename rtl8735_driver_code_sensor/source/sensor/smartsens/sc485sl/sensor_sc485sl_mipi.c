static int sc485sl_get_exposure_gain_info(uint32_t isp_id,
					 const struct rts_isp_sensor_exp_gain *exp_gain,
					 struct rts_isp_sync_regs *regs)
{
	int i;
	int exp_set;
	uint16_t frame_length;
	uint16_t gain_reg[2], exposure_rows[2];
	float exp_reg_value_float;

	float gain;
	struct sc485sl_status *status;
	struct rts_isp_sync_reg *reg;

	if (isp_id >= SUPPORTED_ISP_NUM || !exp_gain || !regs)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];

	frame_length = exp_gain->vts;

	reg = regs->reg;

	if (status->hdr == HDR_MODE) {
	for (i = 0; i < 2; i++) {
		exposure_rows[i] = exp_gain->exposure[i] / status->exp_step + 0.5f;
		gain_reg[i] = get_sensor_gain_reg(exp_gain->analog_gain[i] * exp_gain->digital_gain[i],status);
	}
	
	exposure_rows[0] = clip_d_word(exposure_rows[0], 2, (frame_length - interval_between_long_short - 13));
	exposure_rows[1] = clip_d_word(exposure_rows[1], 2, (interval_between_long_short - 11));

		i = 0;
		
		/* set vts */
		if (abs(status->last_vts - frame_length) > 0.001f) {
			set_sync_i2c(&reg[i++], 0x320e, (frame_length >> 8));
			set_sync_i2c(&reg[i++], 0x320f, (frame_length & 0xff));
			status->last_vts = frame_length;
		}
		
		/* set exposure */	
		if (abs(status->last_exposure[0] - exp_gain->exposure[0]) > 0.001f) {
			set_sync_i2c(&reg[i++], 0x3e20, ((exposure_rows[0] << 4) >> 24 )& 0xff);
			set_sync_i2c(&reg[i++], 0x3e00, ((exposure_rows[0] << 4) >> 16 )& 0xff);
			set_sync_i2c(&reg[i++], 0x3e01, ((exposure_rows[0] << 4) >> 8 )& 0xff);
			set_sync_i2c(&reg[i++], 0x3e02, (exposure_rows[0] << 4) & 0xff);
			status->last_exposure[0] = exp_gain->exposure[0];
		}

		/* set gain */
		if (abs(status->last_gain_reg_num - status->gain_reg_num) > 0.001f) {
			set_sync_i2c(&reg[i++], 0x3e08, (gain_reg[0] >> 8));
			set_sync_i2c(&reg[i++], 0x3e09, (gain_reg[0] & 0xff));
		
			set_sync_i2c(&reg[i++], 0x3e12, (gain_reg[1] >> 8));
			set_sync_i2c(&reg[i++], 0x3e13, (gain_reg[1] & 0xff));
			status->last_gain_reg_num = status->gain_reg_num;
		}

		/* set exposure */	
		if (abs(status->last_exposure[1] - exp_gain->exposure[1]) > 0.001f) {

			//printf("[ExpGain SET]vts=%d, exp[0]=%f, exp[1]=%f\n", frame_length, exp_gain->exposure[0],exp_gain->exposure[1]);
			
			set_sync_i2c(&reg[i++], 0x3e21, ((exposure_rows[1] << 4) >> 24 )& 0xff);
			set_sync_i2c(&reg[i++], 0x3e22, ((exposure_rows[1] << 4) >> 16 )& 0xff);
			set_sync_i2c(&reg[i++], 0x3e04, ((exposure_rows[1] << 4) >> 8 )& 0xff);
			set_sync_i2c(&reg[i++], 0x3e05, (exposure_rows[1] << 4) & 0xff);
			status->last_exposure[1] = exp_gain->exposure[1];
		}
			
		//printf("[ExpGain SET]vts=%d, exp[0]=%f, exp[1]=%f\n", frame_length, exp_gain->exposure[0],exp_gain->exposure[1]);
		//printf("[ExpGain SET]gain_nem=%d, gain_reg[0]=%d, gain_reg[1]=%d\n", status->gain_reg_num,gain_reg[0],gain_reg[1]);

	}
	else{

		exposure_rows[0] = exp_gain->exposure[0] / status->exp_step + 0.5f;
		gain_reg[0] = get_sensor_gain_reg(exp_gain->analog_gain[0] * exp_gain->digital_gain[0],status);
				
		i = 0;
		/* set vts */
		if (abs(status->last_vts - frame_length) > 0.001f) {
			set_sync_i2c(&reg[i++], 0x320e, (frame_length >> 8));
			set_sync_i2c(&reg[i++], 0x320f, (frame_length & 0xff));
			status->last_vts = frame_length;
		}
		
		/* set exposure */	
		if (abs(status->last_exposure[0] - exp_gain->exposure[0]) > 0.001f) {
			set_sync_i2c(&reg[i++], 0x3e20, ((exposure_rows[0] << 4) >> 24 )& 0xff);
			set_sync_i2c(&reg[i++], 0x3e00, ((exposure_rows[0] << 4) >> 16 )& 0xff);
			set_sync_i2c(&reg[i++], 0x3e01, ((exposure_rows[0] << 4) >> 8 )& 0xff);
			set_sync_i2c(&reg[i++], 0x3e02, (exposure_rows[0] << 4) & 0xff);
			status->last_exposure[0] = exp_gain->exposure[0];
		}
		
		/* set gain */
		if (abs(status->last_gain_reg_num - status->gain_reg_num) > 0.001f) {
			set_sync_i2c(&reg[i++], 0x3e08, (gain_reg[0] >> 8));
			set_sync_i2c(&reg[i++], 0x3e09, (gain_reg[0] & 0xff));
			status->last_gain_reg_num = status->gain_reg_num;
		}
		//printf("frame_length=%d, exp[0]=%f, exp[1]=%f\n", frame_length, exp_gain->exposure[0],exp_gain->exposure[1]);
		//printf("gain_nem=%d, gain_reg[0]=%d, gain_reg[1]=%d\n", status->gain_reg_num,gain_reg[0],gain_reg[1]);

	}
	regs->num = i;
	
	return RTS_ISP_OK;
}


static int sc485sl_set_mirror_flip(uint32_t isp_id,
								  struct rts_isp_sensor_mirror_flip *mf_info)
{
	int i;
	uint16_t bySnrImgDir;
	struct rts_isp_sync_reg *reg;

	bySnrImgDir = mf_info->mirror_en != 0;
	bySnrImgDir = (mf_info->flip_en != 0) << 1 | bySnrImgDir;
	mf_info->delay_frames = 1;

	i = 0;
	reg = mf_info->regs.reg;
	switch(bySnrImgDir)
	{
		case 0:	// Normal
		default:
            set_sync_i2c(&reg[i++], 0x3221, 0x00);
			break;
		case 1: // Mirror
           	set_sync_i2c(&reg[i++], 0x3221, 0x06);
			break;
		case 2:	// VFlip
            set_sync_i2c(&reg[i++], 0x3221, 0x60);
			break;
		case 3:	// Rotate
            set_sync_i2c(&reg[i++], 0x3221, 0x66);
			break;
	}
	mf_info->regs.num = i;
	

	return RTS_ISP_OK;
}

static int sc485sl_check(uint32_t isp_id)
{
	int ret;
	int id;
	struct rts_isp_i2c_reg reg;
	int idx = sensor_get_slave_addr_idx();

	if (idx >= SLAVE_ADDR_NUM)
		return -RTS_ISP_EINVAL;

	real_slave_addr = slave_addr_list[idx];

    rts_isp_sensor_access_prepare();
	reg.addr = 0x3107;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	if (ret) {
		rts_isp_sensor_access_unprepare();
		return ret;
	}
	id = reg.data << 8;

	reg.addr = 0x3108;
	ret = rts_isp_read_sensor_reg(isp_id, &reg);
	rts_isp_sensor_access_unprepare();
	if (ret)
		return ret;

	id |= reg.data;

	if (id == 0xbd82)
		return RTS_ISP_OK;
	else
		return -RTS_ISP_EINVAL;
}

