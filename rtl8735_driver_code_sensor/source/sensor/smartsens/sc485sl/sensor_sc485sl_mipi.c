static int sc485sl_get_info(uint32_t isp_id, struct rts_isp_sensor_info *info)
{
	int i;
	struct rts_isp_snr_pwr *up = &info->power_up;
	struct rts_isp_snr_pwr *down = &info->power_down;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	i = 0;
	info->modes.mode[i].hdr = LINEAR_MODE;
	info->modes.mode[i].size.w = 2560;
	info->modes.mode[i].size.h = 1440;
	info->modes.mode[i].fps = g_sc485sl_fps_info_asic_linear_4lane[0].fps;			//@MLCK=24MHz
	i++;
	info->modes.mode[i].hdr = HDR_MODE;
	info->modes.mode[i].size.w = 2560;
	info->modes.mode[i].size.h = 1440;
	info->modes.mode[i].fps = g_sc485sl_fps_info_asic_hdr_4lane[0].fps;			//@MLCK=24MHz
	i++;
	info->modes.num = i;

	info->i2c.i2c_id = real_slave_addr;
	info->i2c.addr_len = 2;
	info->i2c.data_len = 1;

	//g_status->hdr = LINEAR_MODE; //LINEAR_MODE, HDR_MODE
	info->cur_hdr_mode = g_status->hdr;

	i = 0;
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 5000);
	set_power_item(&up->items[i++], SNR_IO_POWER, PWR_1V8, 1000);
	set_power_item(&up->items[i++], SNR_CORE_POWER, PWR_1V5, 1000);
	set_power_item(&up->items[i++], SNR_ANALOG_POWER, PWR_2V8, 5000);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 0);
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_HIGH, 10000);
	set_power_item(&up->items[i++], SNR_HCLK, CLK_24M, 5000);
	up->num = i;
	i = 0;
	set_power_item(&down->items[i++], SNR_RST_GPIO, 0, 0);
	set_power_item(&down->items[i++], SNR_HCLK, 0, 0);
	set_power_item(&down->items[i++], SNR_ANALOG_POWER, 0, 0);
	set_power_item(&down->items[i++], SNR_CORE_POWER, 0, 0);
	set_power_item(&down->items[i++], SNR_IO_POWER, 0, 0);
	down->num = i;

	return RTS_ISP_OK;
}

static const struct fps_info *sc485sl_get_fps_info(uint16_t fps, const struct rts_isp_sensor_mode *mode)
{
	int i;
	if (mode->hdr == HDR_MODE) {
		for (i = 0; i < ARRAY_SIZE(g_sc485sl_fps_info_asic_hdr_4lane); i++)
			if (fps == g_sc485sl_fps_info_asic_hdr_4lane[i].fps)
				break;
		if (i == ARRAY_SIZE(g_sc485sl_fps_info_asic_hdr_4lane))
			return NULL;

		return &g_sc485sl_fps_info_asic_hdr_4lane[i];
	}
	else
	{
		for (i = 0; i < ARRAY_SIZE(g_sc485sl_fps_info_asic_linear_4lane); i++)
			if (fps == g_sc485sl_fps_info_asic_linear_4lane[i].fps)
				break;
		if (i == ARRAY_SIZE(g_sc485sl_fps_info_asic_linear_4lane))
			return NULL;

		return &g_sc485sl_fps_info_asic_linear_4lane[i];
	}
}

static int sc485sl_get_init_info(uint32_t isp_id,
				const struct rts_isp_sensor_mode *mode,
				struct rts_isp_sensor_init_info *info)
{
	const struct fps_info *fps_info;
	struct sc485sl_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
		return -RTS_ISP_EINVAL;

	status = &g_status[isp_id];
	status->hdr = mode->hdr;
	//printf("sc485sl_get_init_info hdr: %x fps: %d\n\r", mode->hdr, mode->fps);
	fps_info = sc485sl_get_fps_info(mode->fps, &mode->hdr);

	if (!fps_info)
		return -RTS_ISP_EINVAL;

	if (mode->hdr == HDR_MODE) {
		//printf("sc485sl_get_init_info HDR mode\n\r");
		set_init_i2c_regs(info->sensor_regs[0],
				  g_sc485sl_i2c_init_regs_asic_hdr_4lane, 0);
		
		info->interface.interface = SNR_INTERFACE_MIPI;
		info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1 | MIPI_LANE2 | MIPI_LANE3;
		info->interface.mipi.hs_term = 0x5;
		info->interface.type = RAW_SENSOR;
		info->interface.bit_depth = SNR_10BIT;
		info->mipi_behavor = VC_HDR;
		
		info->size.w = 2560;
		info->size.h = 1440;
		info->start.x = 0;
		info->start.y = 0;
		
		info->hts = fps_info->hts ;
		info->min_vts = status->min_vts = fps_info->vts;
		info->pclk = fps_info->clk;
		info->max_vts = info->min_vts * 30;
		
		status->exp_step = 1e6 * info->hts / info->pclk; /* 3306 /198.4 =  16.66us */
	}
	else{
		//printf("sc485sl_get_init_info linear mode\n\r");
		set_init_i2c_regs(info->sensor_regs[0],
				  g_sc485sl_i2c_init_regs_asic_linear_4lane, 0);

		info->interface.interface = SNR_INTERFACE_MIPI;
		info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1 | MIPI_LANE2 | MIPI_LANE3;
		info->interface.mipi.hs_term = 0x5;
		info->interface.type = RAW_SENSOR;
		info->interface.bit_depth = SNR_10BIT;
		info->mipi_behavor = NONE_HDR;

		info->size.w = 2560;
		info->size.h = 1440;
		info->start.x = 0;
		info->start.y = 0;

		info->hts = fps_info->hts ;
		info->min_vts = status->min_vts = fps_info->vts;
		info->pclk = fps_info->clk;
	info->max_vts = info->min_vts * 30;

		status->exp_step = 1e6 * info->hts / info->pclk; /* 3097 /198.4 =  15.61us */
	}

	return RTS_ISP_OK;
}
