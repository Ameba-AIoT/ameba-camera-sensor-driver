static int imx775_get_info(uint32_t isp_id, struct rts_isp_sensor_info *info)
{
	int i;
	struct rts_isp_snr_pwr *up = &info->power_up;
	struct rts_isp_snr_pwr *down = &info->power_down;
	//debug("@ imx775_get_info isp_id = %d\n",isp_id);

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
	{		printf("howard_log1\n");
		return -RTS_ISP_EINVAL;
	}

	info->modes.mode[0].hdr = LINEAR_MODE;//RTS_ISP_HDR_NONE;
	info->modes.mode[0].size.w = 2592; //2592
	info->modes.mode[0].size.h = 1944; //1944
	info->modes.mode[0].fps = g_imx775_fps_info_asic[0].fps;
	info->modes.num = 1;
	
	info->i2c.i2c_id = 0x1B;
	info->i2c.addr_len = 2;
	info->i2c.data_len = 1;
	info->cur_hdr_mode = g_status->hdr;

	i = 0;
	set_power_item(&up->items[i++], SNR_HCLK, CLK_24M, 100);
	//set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 200);
    set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_LOW, 0);
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_LOW, 100);
	//set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_HIGH, 300);
	set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_HIGH, 100);
	set_power_item(&up->items[i++], SNR_RST_GPIO, GPIO_HIGH, 5000);
	//set_power_item(&up->items[i++], SNR_PWDN_GPIO, GPIO_HIGH, 5000);
	

	up->num = i;
	i = 0;
	
	set_power_item(&down->items[i++], SNR_RST_GPIO, GPIO_LOW, 1);
	set_power_item(&down->items[i++], SNR_HCLK, CLK_NONE, 1);
	down->num = i;

	return RTS_ISP_OK;
}

static const struct fps_info *imx775_get_fps_info(uint16_t fps)
{
	int i;
	for (i = 0; i < ARRAY_SIZE(g_imx775_fps_info_asic); i++)
		if (fps == g_imx775_fps_info_asic[i].fps)
			break;
	if (i == ARRAY_SIZE(g_imx775_fps_info_asic))
		return NULL;
	return &g_imx775_fps_info_asic[i];

}

static int imx775_get_init_info(uint32_t isp_id,
				const struct rts_isp_sensor_mode *mode,
				struct rts_isp_sensor_init_info *info)
{
	const struct fps_info *fps_info;
	struct imx775_status *status;

	if (isp_id >= SUPPORTED_ISP_NUM || !info)
	{		printf("howard_log2\n");
		return -RTS_ISP_EINVAL;
	}
	//printf("imx775 get fps %u init info\n", fps);

	status = &g_status[isp_id];
	status->hdr = mode->hdr;

	fps_info = imx775_get_fps_info(mode->fps);
	if (!fps_info)
	{		printf("howard_log3\n");
		return -RTS_ISP_EINVAL;
	}
	set_init_i2c_regs(info->sensor_regs[0], g_imx775_i2c_init_regs_standby, 5000);
	set_init_i2c_regs(info->sensor_regs[1], g_imx775_i2c_init_regs_auth, 0);
	set_init_i2c_regs(info->sensor_regs[2], g_imx775_i2c_init_regs_mode_setting, 0);
	//set_init_i2c_regs(info->sensor_regs[3], g_imx775_i2c_init_regs_mode_setting_chunk2, 0);
	//set_init_i2c_regs(info->sensor_regs[4], g_imx775_i2c_init_regs_mode_setting_chunk3, 0);
	//set_init_i2c_regs(info->sensor_regs[5], g_imx775_i2c_init_regs_mode_setting_chunk4, 0);
	//set_init_i2c_regs(info->sensor_regs[6], g_imx775_i2c_init_regs_mode_setting_chunk5, 0);
	set_init_i2c_regs(info->sensor_regs[3], g_imx775_i2c_init_regs_streaming, 0);
	
	info->interface.interface = SNR_INTERFACE_MIPI;
	info->interface.mipi.lanes = MIPI_LANE0 | MIPI_LANE1;
	info->interface.mipi.hs_term = 0x5;
	info->interface.type = RAW_SENSOR;
	info->interface.bit_depth = SNR_12BIT;
	info->mipi_behavor = NONE_HDR;
	info->size.w = 2592;
	info->size.h = 1944;
	info->start.x = 0;
	info->start.y = 0;
	info->hts = fps_info->hts;
	info->pclk = fps_info->clk;
	info->min_vts = status->min_vts = 2148;
	info->max_vts = info->min_vts * 30;
	
	status->exp_step = 1e6 * info->hts / info->pclk; /* us */
	return RTS_ISP_OK;
}
