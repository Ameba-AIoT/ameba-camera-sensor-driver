#define TNR_CTRL (TNR_REG_BASE + 0x0000)
#define TNR_STREAM_BUF_CFG (TNR_REG_BASE + 0x03D0)

#define IVE_REG_BASE 0x11000
#define IVE_ENABLE (IVE_REG_BASE + 0x0000)
#define IVE_NORM_MEAN (IVE_REG_BASE + 0x0004)
#define IVE_NORM_SCALE (IVE_REG_BASE + 0x0008)
#define IVE_QUANT_LEN (IVE_REG_BASE + 0x000C)
#define IVE_ASYM_INV_SCALE (IVE_REG_BASE + 0x0010)
#define IVE_ASYM_ZERO_POINT (IVE_REG_BASE + 0x0014)

/* SYS_IMAGE_SEL0 */
#define SEL_FINAL_OUTPUT 0x0
