#define ZOOM_CH0_SCALE_UP_EN (ZOOM_REG_BASE + 0x002C)
#define ZOOM_CH0_STEP_V (ZOOM_REG_BASE + 0x0048)
#define ZOOM_CH0_STEP_H (ZOOM_REG_BASE + 0x004C)
#define ZOOM_CH0_REG_LOAD (ZOOM_REG_BASE + 0x0024)
#define ZOOM_CH_REG_OFFSET 0x80

#define STATIS_REG_BASE 0xb800
#define STATIS_CTRL (STATIS_REG_BASE + 0x0000)
#define STATIS_DDR_ADDR (STATIS_REG_BASE + 0x000C)
#define STATIS_DDR_LEN (STATIS_REG_BASE + 0x0010)
#define STATIS_BUF_SIZE (STATIS_REG_BASE + 0x0014)
#define STATIS_BLOCK_EN (STATIS_REG_BASE + 0x0020)

